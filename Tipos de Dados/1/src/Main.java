// 1.Declare uma variável de cada tipo primitivo (int, double, char, boolean, long, float, byte, short) e imprima seus valores.
public class Main {
    public static void main(String[] args) {
        int a = 12;
        double b = 3.14;
        char c = 'B';
        boolean d = true;
        long e = 983913981739L;
        float f = 0.1F;
        byte g = 10;
        short h = 1;

        System.out.println("Inteiro: " + a);
        System.out.println("Double: " + b);
        System.out.println("Char: " + c);
        System.out.println("Boleano: " + d);
        System.out.println("Long: " + e);
        System.out.println("Float: " + f);
        System.out.println("Byte: " + g);
        System.out.println("Short: " + h);
    }
}